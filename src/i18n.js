  let currentLang = 'es';

  function t(key, vars) {
    const table = DICT[currentLang] || DICT.es;
    let str = (table && table[key] != null) ? table[key] : (DICT.es[key] != null ? DICT.es[key] : key);
    if (vars) {
      for (const k of Object.keys(vars)) {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      }
    }
    return str;
  }

  function setLanguage(lang) {
    currentLang = (lang === 'en') ? 'en' : 'es';
    document.documentElement.lang = currentLang;
  }

  function getLanguage() {
    return currentLang;
  }

  // ---- Traducción de textos ya guardados (ej. el "label" de calidad que se
  // guarda en el historial) ----
  // Esos textos se guardan tal cual en el idioma activo al momento de la
  // descarga, así que si el usuario cambia de idioma después, quedan
  // "congelados" en el idioma viejo. Estas son las claves cuyo VALOR puede
  // terminar guardado como texto plano en algún lado (historial, etc.);
  // acá se arma un mapa inverso (texto conocido en cualquier idioma -> clave)
  // para poder re-traducirlos al idioma actual en el momento de mostrarlos.
  const TRANSLATABLE_LABEL_KEYS = [
    'best_video_audio',
    'best_audio',
    'opt_quality_best',
    'opt_quality_audio',
    'opt_quality_audio_m4a',
    'opt_quality_audio_opus',
    'opt_quality_2160',
    'opt_quality_1440',
    'opt_quality_1080',
    'opt_quality_720',
    'opt_quality_480',
    'opt_quality_360',
    'opt_quality_240',
    'opt_quality_144',
  ];

  let knownTextToKey = null; // se arma una sola vez (lazy) y se cachea
  function buildKnownTextMap() {
    const map = new Map();
    for (const lang of Object.keys(DICT)) {
      const table = DICT[lang];
      for (const key of TRANSLATABLE_LABEL_KEYS) {
        const value = table[key];
        if (value != null) map.set(value, key);
      }
    }
    return map;
  }

  // Si `text` coincide exactamente con el valor conocido de alguna de las
  // claves de arriba (en cualquier idioma), devuelve esa clave traducida al
  // idioma ACTUAL. Si no coincide con nada conocido (ej. un preset con
  // nombre propio del usuario, o "1080p"), devuelve el texto sin tocar.
  function translateKnownText(text) {
    if (!text) return text;
    if (!knownTextToKey) knownTextToKey = buildKnownTextMap();
    const key = knownTextToKey.get(text);
    return key ? t(key) : text;
  }



  // Recorre el DOM y aplica las traducciones a todos los elementos marcados
  // con data-i18n (texto), data-i18n-placeholder y data-i18n-title (atributos).
  function applyTranslations(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    // Caso especial: el hint del archivo de cookies tiene una ruta en <code> en
    // medio de la oración, así que se arma a mano en vez de usar textContent.
    const cookiesFileHint = scope.querySelector('#setting-cookies-file-row .settings-hint');
    if (cookiesFileHint) {
      cookiesFileHint.textContent = '';
      cookiesFileHint.appendChild(document.createTextNode(t('cookies_file_hint_pre')));
      const code = document.createElement('code');
      code.textContent = '%AppData%\\yt-dlp-interface\\file-cookies';
      cookiesFileHint.appendChild(code);
      cookiesFileHint.appendChild(document.createTextNode(t('cookies_file_hint_post')));
    }
  }

  window.i18n = { t, setLanguage, getLanguage, applyTranslations, translateKnownText };
